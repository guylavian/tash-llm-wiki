#!/usr/bin/env python3
"""crosslink.py — bridge synthesized pages to their reference notes with [[wikilinks]].

Obsidian's graph only draws `[[wikilink]]` edges. Synthesized pages cite the KB via
`kb:` / `ref:` provenance tokens in their `sources:` block (plain YAML, not links), so
the wiki and the `reference/<domain>/` tier render as two disconnected clusters. This
tool resolves each page's `kb:<tail>` token to the matching reference note — the note
whose `source:` URL ends with that tail, preferring the `primary` (newest) version —
and writes a generated **## Sources** section of `[[links]]` into the page body. That
makes the wiki → KB connection visible in the graph.

The `sources:` provenance block is left untouched (manifest/lint still parse it); only a
marked `## Sources` section is added/refreshed, so the tool is idempotent. stdlib only.

Usage:
    python3 wiki/_meta/bin/crosslink.py            # dry-run: counts + a sample
    python3 wiki/_meta/bin/crosslink.py --apply    # write the ## Sources sections
"""
import argparse
import os
import re

BIN = os.path.dirname(os.path.abspath(__file__))
WIKI = os.path.dirname(os.path.dirname(BIN))
REF = os.path.join(WIKI, "reference")
PAGE_DIRS = ("topics", "entities", "questions")
FM_RE = re.compile(r"^---\n(.*?)\n---", re.DOTALL)
BEGIN = "<!-- crosslink:begin (generated by crosslink.py — do not edit) -->"
END = "<!-- crosslink:end -->"
SECTION_RE = re.compile(r"\n*## Sources\n" + re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n*",
                        re.DOTALL)


def unquote(s):
    s = s.strip()
    if len(s) >= 2 and s[0] == s[-1] and s[0] in "\"'":
        return s[1:-1]
    return s


def top_fields(block):
    fm = {}
    for line in block.splitlines():
        if line and not line[0].isspace() and ":" in line and not line.startswith(("-", "#")):
            k, _, v = line.partition(":")
            fm[k.strip()] = unquote(v)
    return fm


def source_tokens(block):
    """kb:/ref:/guide:/note:/web: tokens listed under `sources:` in the frontmatter."""
    out, in_src = [], False
    for line in block.splitlines():
        if re.match(r"^sources:\s*$", line):
            in_src = True
            continue
        if in_src:
            m = re.match(r"^\s*-\s*((?:kb|guide|ref|note|web):\S+)", line)
            if m:
                out.append(m.group(1))
            elif not line.startswith((" ", "\t", "-")):
                break
    return out


def url_tail(url):
    return (url or "").rstrip("/").rsplit("/", 1)[-1]


def vkey(v):
    try:
        return tuple(int(x) for x in (v or "0").split("."))
    except ValueError:
        return (0,)


def build_ref_index():
    """domain -> url_tail -> list of {slug,title,primary,version}."""
    idx = {}
    if not os.path.isdir(REF):
        return idx
    for dom in sorted(os.listdir(REF)):
        dd = os.path.join(REF, dom)
        if not os.path.isdir(dd):
            continue
        for fn in sorted(os.listdir(dd)):
            if not fn.endswith(".md") or fn == "_gated-kb-index.md":
                continue
            m = FM_RE.match(open(os.path.join(dd, fn), encoding="utf-8").read())
            fm = top_fields(m.group(1)) if m else {}
            tail = url_tail(fm.get("source")).rstrip("-")   # RHBK URLs vary on the trailing dash
            if not tail:
                continue
            idx.setdefault(dom, {}).setdefault(tail, []).append({
                "slug": fn[:-3],
                "title": fm.get("title") or fn[:-3],
                "primary": str(fm.get("primary")).lower() == "true",
                "version": fm.get("version") or "",
            })
    return idx


def resolve(token, domain, idx):
    """A kb:<tail> token -> the best-matching reference note dict, or None."""
    if not token.startswith("kb:"):
        return None  # guide:/ref:/web:/note: don't map 1:1 to a reference note
    # tokens come as kb:<tail>, kb:<guide>/<tail>, or kb:<full-url> — match the last
    # segment, normalizing the trailing dash that RHBK doc URLs inconsistently carry
    tail = url_tail(token[len("kb:"):]).rstrip("-")
    cands = (idx.get(domain) or {}).get(tail)
    if not cands:
        return None
    cands = sorted(cands, key=lambda c: (c["primary"], vkey(c["version"])), reverse=True)
    return cands[0]


def short_title(t):
    # strip chars that would break a [[slug|alias]] (titles like "[RHBK] ..." contain ])
    return re.sub(r"[\[\]|#]", "", (t or "").split(" - ")[0]).strip()


def build_section(links):
    body = "\n".join(f"- [[{slug}|{short_title(title)}]]" for slug, title in links)
    return f"\n\n## Sources\n{BEGIN}\n{body}\n{END}\n"


def apply_section(text, links):
    if links:
        block = build_section(links)
        if SECTION_RE.search(text):
            return SECTION_RE.sub(block, text)
        return text.rstrip() + block
    # no links: strip any stale generated section
    return SECTION_RE.sub("\n", text) if SECTION_RE.search(text) else text


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--apply", action="store_true")
    args = ap.parse_args()

    idx = build_ref_index()
    pages_linked = edges = 0
    unresolved = {}
    sample = None

    for d in PAGE_DIRS:
        full = os.path.join(WIKI, d)
        if not os.path.isdir(full):
            continue
        for fn in sorted(os.listdir(full)):
            if not fn.endswith(".md") or fn == "README.md":
                continue
            path = os.path.join(full, fn)
            text = open(path, encoding="utf-8").read()
            m = FM_RE.match(text)
            if not m:
                continue
            fm = top_fields(m.group(1))
            domain = fm.get("domain")
            links, seen = [], set()
            for tok in source_tokens(m.group(1)):
                r = resolve(tok, domain, idx)
                if r and r["slug"] not in seen:
                    seen.add(r["slug"])
                    links.append((r["slug"], r["title"]))
                elif tok.startswith("kb:") and not r:
                    unresolved[tok] = unresolved.get(tok, 0) + 1
            if links:
                pages_linked += 1
                edges += len(links)
                if sample is None:
                    sample = (fn[:-3], links)
            new = apply_section(text, links)
            if args.apply and new != text:
                with open(path, "w", encoding="utf-8") as fh:
                    fh.write(new)

    print(f"{'WROTE' if args.apply else 'DRY RUN'} — {pages_linked} pages → {edges} wiki→KB edges")
    if unresolved:
        top = sorted(unresolved.items(), key=lambda kv: -kv[1])[:8]
        print(f"unresolved kb: tokens (no reference note — likely gated/solution ids): "
              f"{len(unresolved)} distinct; e.g. " + ", ".join(f"{t}×{n}" for t, n in top))
    if sample:
        slug, links = sample
        print(f"\nsample — {slug}.md ## Sources:")
        for s, t in links:
            print(f"  - [[{s}|{short_title(t)}]]")
    if not args.apply:
        print("\nRe-run with --apply to write.")


if __name__ == "__main__":
    main()
