#!/usr/bin/env python3
"""index.py — (re)generate the wiki's routing indexes. stdlib only, no network.

Builds one `index.<domain>.md` per declared domain (the per-domain routing index:
page titles + one-line summaries, grouped by type) and refreshes a generated
"Domains" router block inside the global `index.md`. The per-domain index is the
surface a QUERY loads to stay inside a local model's context window as the wiki
grows to many domains — so it lists *only* slugs + summaries, never bodies.

Generated `index.<domain>.md` files are owned by this tool — never hand-edit them
(regenerate instead). The curated `index.md` is left intact except for the marked
router block. `lint.py` warns when an index is stale (run `index.py --check`).

Usage:
    python3 -m wikikb index            # write index.<domain>.md + refresh index.md router (from _meta/)
    python3 -m wikikb index --check    # report drift without writing (exit 1 if stale)
"""
import argparse
import os
import re
import sys

from wikikb import paths
META = str(paths.META)
WIKI = str(paths.WIKI)
REF = str(paths.REFERENCE)
TAXONOMY = str(paths.TAXONOMY)
PAGE_DIRS = paths.PAGE_DIRS
FM_RE = re.compile(r"^---\n(.*?)\n---", re.DOTALL)
ROUTER_BEGIN = "<!-- index.py:domains:begin (generated — do not edit) -->"
ROUTER_END = "<!-- index.py:domains:end -->"
DOMAIN_RE = re.compile(r"^\s*-\s*domain:\s*([a-z][a-z0-9-]*)\s*$")
META_RE = re.compile(r"^\s*-\s*(review-moc|shape):\s*(\S.*?)\s*$")

sys.dont_write_bytecode = True
try:
    from wikikb.build import tags as tagmod
except Exception:  # noqa: BLE001
    tagmod = None


def unquote(s):
    s = s.strip()
    if len(s) >= 2 and s[0] == s[-1] and s[0] in "\"'":
        return s[1:-1]
    return s


def frontmatter(text):
    m = FM_RE.match(text)
    if not m:
        return {}
    fm = {}
    for line in m.group(1).splitlines():
        if line and not line[0].isspace() and not line.startswith(("-", "#")) and ":" in line:
            k, _, v = line.partition(":")
            fm[k.strip()] = unquote(v)
    return fm


def collect():
    """domain -> type -> sorted list of (slug, summary)."""
    out = {}
    for d in PAGE_DIRS:
        full = os.path.join(WIKI, d)
        if not os.path.isdir(full):
            continue
        for fn in sorted(os.listdir(full)):
            if not fn.endswith(".md") or fn == "README.md":
                continue
            slug = fn[:-3]
            with open(os.path.join(full, fn), encoding="utf-8") as fh:
                fm = frontmatter(fh.read())
            dom = fm.get("domain") or "unfiled"
            typ = fm.get("type") or d.rstrip("s")
            summary = fm.get("summary") or ""
            out.setdefault(dom, {}).setdefault(typ, []).append((slug, summary))
    for dom in out:
        for typ in out[dom]:
            out[dom][typ].sort()
    return out


def domain_meta():
    """domain -> {review-moc, shape} parsed from the ## Domains blocks in taxonomy.md."""
    meta = {}
    if not os.path.isfile(TAXONOMY):
        return meta
    cur = None
    in_comment = False
    with open(TAXONOMY, encoding="utf-8") as fh:
        for line in fh:
            if in_comment:                 # skip the <!-- template --> block entirely
                if "-->" in line:
                    in_comment = False
                continue
            if "<!--" in line:
                in_comment = "-->" not in line
                continue
            if line.lstrip().startswith("#"):
                cur = None                 # a new heading ends the current block
            dm = DOMAIN_RE.match(line)
            if dm:
                cur = dm.group(1)
                meta.setdefault(cur, {})
                continue
            if cur:
                mm = META_RE.match(line)
                if mm:
                    meta[cur][mm.group(1)] = mm.group(2)
    return meta


def declared_domains():
    if tagmod is not None:
        return tagmod.load_domains()
    return set(domain_meta())


def render_domain_index(domain, by_type):
    lines = [f"# {domain} — routing index", "",
             f"_Generated by `python3 -m wikikb index` — do not hand-edit. The per-domain routing "
             f"surface for the `{domain}` domain (titles + summaries) read during the tiered "
             f"QUERY cheap pass; regenerate after ingest._", ""]
    order = [("topic", "Topics"), ("entity", "Entities"), ("question", "Questions")]
    done = set()
    n = 0

    def emit(label, items):
        nonlocal n
        lines.append(f"## {label} ({len(items)})")
        for slug, summary in items:
            lines.append(f"- [[{slug}]]" + (f" — {summary}" if summary else ""))
        lines.append("")
        n += len(items)

    for key, label in order:
        if by_type.get(key):
            emit(label, by_type[key])
            done.add(key)
    for typ, items in sorted(by_type.items()):
        if typ not in done and items:
            emit(typ, items)
    lines.insert(3, f"**{n} pages.**\n")
    return "\n".join(lines).rstrip() + "\n"


def render_router(pages, meta):
    rows = [ROUTER_BEGIN, "## Domains",
            "_Per-domain routing indexes (generated). A QUERY routes here first, then opens the "
            "relevant index below to stay inside the model's context window._", ""]
    for dom in sorted(pages):
        count = sum(len(v) for v in pages[dom].values())
        moc = (meta.get(dom) or {}).get("review-moc")
        suffix = f" · review lens [[{moc}]]" if moc else ""
        refdir = os.path.join(WIKI, "reference", dom)
        nref = len([f for f in os.listdir(refdir)
                    if f.endswith(".md") and not f.startswith("_")]) if os.path.isdir(refdir) else 0
        refnote = f" · [[_ref-{dom}|{nref} reference notes]]" if nref else ""
        rows.append(f"- [{dom}](index.{dom}.md) — {count} pages{refnote}{suffix}")
    rows.append(ROUTER_END)
    return "\n".join(rows)


def update_global_index(pages, meta, write):
    path = os.path.join(WIKI, "index.md")
    text = open(path, encoding="utf-8").read() if os.path.exists(path) else "# Wiki — Index\n"
    block = render_router(pages, meta)
    if ROUTER_BEGIN in text and ROUTER_END in text:
        new = re.sub(re.escape(ROUTER_BEGIN) + ".*?" + re.escape(ROUTER_END),
                     lambda _m: block, text, flags=re.DOTALL)
    else:
        idx = text.find("\n## ")
        if idx == -1:
            new = text.rstrip() + "\n\n" + block + "\n"
        else:
            new = text[:idx + 1] + block + "\n\n" + text[idx + 1:]
    changed = new != text
    if changed and write:
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(new)
    return changed


def _short(t):
    # strip chars that would break a [[slug|alias]] (titles like "[RHBK] ..." contain ])
    return re.sub(r"[\[\]|#]", "", (t or "").split(" - ")[0]).strip()


def _safe(s):
    return re.sub(r"[^a-z0-9_-]+", "-", (s or "").lower()).strip("-") or "other"


def ref_group_key(fm):
    """Group a reference note by its guide (or, for docs-harvested corpora, its family/book); non-doc records by kind."""
    g = fm.get("guide") or fm.get("family")
    if g:
        return g
    k = (fm.get("documentKind") or "other").lower()
    return {"solution": "solutions", "article": "articles", "discussion": "discussions"}.get(k, k)


def collect_reference():
    """domain -> group -> sorted [(slug, title)] for body reference notes (skips `_*` indexes)."""
    out = {}
    if not os.path.isdir(REF):
        return out
    for dom in sorted(os.listdir(REF)):
        dd = os.path.join(REF, dom)
        if not os.path.isdir(dd):
            continue
        for fn in sorted(os.listdir(dd)):
            if not fn.endswith(".md") or fn.startswith("_"):
                continue  # skip the generated hub/group indexes and _gated-kb-index
            with open(os.path.join(dd, fn), encoding="utf-8") as fh:
                fm = frontmatter(fh.read())
            out.setdefault(dom, {}).setdefault(ref_group_key(fm), []).append(
                (fn[:-3], fm.get("title") or fn[:-3]))
    for dom in out:
        for g in out[dom]:
            out[dom][g].sort()
    return out


def render_ref_group(dom, grp, items):
    slug = f"_ref-{dom}-{_safe(grp)}"
    lines = ["---", f"title: {dom} reference — {grp}", "type: reference",
             f"domain: {dom}", f"slug: {slug}", "tier: reference", "---", "",
             f"# {dom} reference — {grp} ({len(items)})", "",
             f"_Generated by `index.py` — links every `reference/{dom}/` note in the "
             f"**{grp}** group so the KB is fully connected in the graph._", ""]
    for s, t in items:
        lines.append(f"- [[{s}|{_short(t)}]]")
    return slug, "\n".join(lines).rstrip() + "\n"


def render_ref_hub(dom, groups, has_gated):
    slug = f"_ref-{dom}"
    total = sum(len(v) for v in groups.values())
    lines = ["---", f"title: {dom} reference index", "type: reference",
             f"domain: {dom}", f"slug: {slug}", "tier: reference", "---", "",
             f"# {dom} reference index", "",
             f"_Generated by `index.py` — the hub for the immutable `reference/{dom}/` tier "
             f"(the folded-in corpus). This is what keeps every KB note connected in the graph._", "",
             f"**{total} reference notes across {len(groups)} groups.**", ""]
    for grp in sorted(groups):
        lines.append(f"- [[_ref-{dom}-{_safe(grp)}|{grp}]] ({len(groups[grp])})")
    if has_gated:
        lines.append("- [[_gated-kb-index|gated KB pointers]]")
    return slug, "\n".join(lines).rstrip() + "\n"


def build_reference_indexes(write):
    """Write per-group + hub index notes that link every reference note (no orphans)."""
    refs = collect_reference()
    written = 0
    for dom, groups in refs.items():
        dd = os.path.join(REF, dom)
        has_gated = os.path.exists(os.path.join(dd, "_gated-kb-index.md"))
        for grp, items in groups.items():
            slug, content = render_ref_group(dom, grp, items)
            if write:
                with open(os.path.join(dd, slug + ".md"), "w", encoding="utf-8") as fh:
                    fh.write(content)
            written += 1
        slug, content = render_ref_hub(dom, groups, has_gated)
        if write:
            with open(os.path.join(dd, slug + ".md"), "w", encoding="utf-8") as fh:
                fh.write(content)
        written += 1
    return refs, written


def stale_indexes():
    """Domains whose index.<domain>.md is missing or out of date (for lint)."""
    pages = collect()
    stale = []
    for dom, by_type in pages.items():
        if dom == "unfiled":
            continue
        path = os.path.join(WIKI, f"index.{dom}.md")
        want = render_domain_index(dom, by_type)
        have = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if have != want:
            stale.append(dom)
    return stale


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true", help="report drift without writing (exit 1 if stale)")
    args = ap.parse_args()

    pages = collect()
    meta = domain_meta()
    declared = declared_domains()

    # warn about pages whose domain isn't declared in taxonomy
    undeclared = sorted(d for d in pages if d not in declared and d != "unfiled")
    if undeclared:
        print("WARN: pages use undeclared domain(s): " + ", ".join(undeclared) +
              " (add a block under ## Domains in taxonomy.md)")
    if "unfiled" in pages:
        print(f"WARN: {sum(len(v) for v in pages['unfiled'].values())} page(s) have no `domain:` "
              "(run backfill.py)")

    if args.check:
        stale = stale_indexes()
        router_drift = update_global_index(pages, meta, write=False)
        if stale or router_drift:
            if stale:
                print("STALE index.<domain>.md: " + ", ".join(stale))
            if router_drift:
                print("STALE index.md domains router")
            sys.exit(1)
        print("Indexes up to date.")
        return

    written = []
    for dom, by_type in pages.items():
        if dom == "unfiled":
            continue
        path = os.path.join(WIKI, f"index.{dom}.md")
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(render_domain_index(dom, by_type))
        written.append((dom, sum(len(v) for v in by_type.values())))
    router_changed = update_global_index(pages, meta, write=True)
    for dom, n in sorted(written):
        print(f"wrote index.{dom}.md ({n} pages)")
    print("refreshed index.md domains router" if router_changed else "index.md router unchanged")

    refs, nwritten = build_reference_indexes(write=True)
    nnotes = sum(sum(len(v) for v in g.values()) for g in refs.values())
    if nwritten:
        print(f"wrote {nwritten} reference index notes linking {nnotes} KB notes (graph backbone)")


if __name__ == "__main__":
    main()
