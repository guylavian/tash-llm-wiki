#!/usr/bin/env python3
"""crosslink.py — bridge synthesized pages to their reference notes with [[wikilinks]].

Obsidian's graph only draws `[[wikilink]]` edges. Synthesized pages cite the KB via
`kb:` / `ref:` / `guide:` provenance tokens in their `sources:` block (plain YAML, not
links), so the wiki and the raw tiers render as disconnected clusters. This tool resolves
each page's `kb:<tail>` token to the matching reference note (the note whose `source:`
URL ends with that tail, preferring the `primary` (newest) version), each `ref:<name>`
token to the curated `references/<name>.md` guide, and each `guide:<slug>` token to the
generated per-guide index note `reference/<domain>/_ref-<domain>-<slug>.md` — and writes
a generated **## Sources** section of `[[links]]` into the page body. That makes the
wiki → raw-tier connection visible in the graph.

The `sources:` provenance block is left untouched (manifest/lint still parse it); only a
marked `## Sources` section is added/refreshed, so the tool is idempotent. stdlib only.

Usage:
    python3 -m wikikb crosslink            # dry-run: counts + a sample
    python3 -m wikikb crosslink --apply    # write the ## Sources sections
"""
import argparse
import os
import re

from wikikb import paths
WIKI = str(paths.WIKI)
REF = str(paths.REFERENCE)
REFS = str(paths.REFERENCES)
PAGE_DIRS = ("topics", "entities", "questions")
FM_RE = re.compile(r"^---\n(.*?)\n---", re.DOTALL)
BEGIN = "<!-- crosslink:begin (generated by crosslink.py — do not edit) -->"
END = "<!-- crosslink:end -->"
SECTION_RE = re.compile(r"\n*## Sources\n" + re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n*",
                        re.DOTALL)


def unquote(s):
    s = s.strip()
    if len(s) >= 2 and s[0] == s[-1] and s[0] in "\"'":
        return s[1:-1]
    return s


def top_fields(block):
    fm = {}
    for line in block.splitlines():
        if line and not line[0].isspace() and ":" in line and not line.startswith(("-", "#")):
            k, _, v = line.partition(":")
            fm[k.strip()] = unquote(v)
    return fm


def source_tokens(block):
    """kb:/ref:/guide:/note:/web: tokens listed under `sources:` in the frontmatter."""
    out, in_src = [], False
    for line in block.splitlines():
        if re.match(r"^sources:\s*$", line):
            in_src = True
            continue
        if in_src:
            m = re.match(r"^\s*-\s*((?:kb|guide|ref|note|web):\S+)", line)
            if m:
                out.append(m.group(1))
            elif not line.startswith((" ", "\t", "-")):
                break
    return out


def url_tail(url):
    return (url or "").rstrip("/").rsplit("/", 1)[-1]


def vkey(v):
    try:
        return tuple(int(x) for x in (v or "0").split("."))
    except ValueError:
        return (0,)


def build_ref_index():
    """domain -> url_tail -> list of {slug,title,primary,version}."""
    idx = {}
    if not os.path.isdir(REF):
        return idx
    for dom in sorted(os.listdir(REF)):
        dd = os.path.join(REF, dom)
        if not os.path.isdir(dd):
            continue
        for fn in sorted(os.listdir(dd)):
            if not fn.endswith(".md") or fn == "_gated-kb-index.md":
                continue
            m = FM_RE.match(open(os.path.join(dd, fn), encoding="utf-8").read())
            fm = top_fields(m.group(1)) if m else {}
            tail = url_tail(fm.get("source")).rstrip("-")   # RHBK URLs vary on the trailing dash
            entry = {
                "slug": fn[:-3],
                "title": fm.get("title") or fn[:-3],
                "primary": str(fm.get("primary")).lower() == "true",
                "version": fm.get("version") or "",
                "family": fm.get("family") or "",   # tkg supersession needs same-family scoping
            }
            # Index by url-tail (the canonical token) AND by the note's own slug, so a page that
            # cites `kb:<slug>` (e.g. kb:rhbk-26-4-caching) resolves even when the source URL tail
            # differs from the slug (e.g. .../caching-). Slug is unique per note, so it's exact.
            keys = {k for k in (tail, fn[:-3]) if k}
            for k in keys:
                idx.setdefault(dom, {}).setdefault(k, []).append(entry)
    return idx


def build_refs_index():
    """Curated references/ guides (the ref: tier): <stem> -> {slug: 'references/<stem>', title}.
    The link target is path-qualified because three stems (server-configuration, rhbk-operator,
    securing-apps-oidc-saml) collide with synthesized-page slugs — a bare [[stem]] would resolve
    to the wrong file in Obsidian."""
    refs = {}
    if not os.path.isdir(REFS):
        return refs
    for fn in sorted(os.listdir(REFS)):
        if not fn.endswith(".md"):
            continue
        text = open(os.path.join(REFS, fn), encoding="utf-8").read()
        m = re.search(r"^# (.+)$", text, re.MULTILINE)
        refs[fn[:-3]] = {"slug": "references/" + fn[:-3],
                         "title": m.group(1).strip() if m else fn[:-3]}
    return refs


def resolve(token, domain, idx):
    """A kb:<tail> token -> the best-matching reference note dict, or None.
    kb:-only ON PURPOSE — tkg/model.py reuses this for CITES edges; ref:/guide: live in
    resolve_any() so extending crosslink's links never changes the graph's edge set."""
    if not token.startswith("kb:"):
        return None  # web:/note: don't map 1:1 to a reference note; ref:/guide: -> resolve_any
    # tokens come as kb:<tail>, kb:<guide>/<tail>, or kb:<full-url> — match the last
    # segment, normalizing the trailing dash that RHBK doc URLs inconsistently carry
    tail = url_tail(token[len("kb:"):]).rstrip("-")
    cands = (idx.get(domain) or {}).get(tail)
    if not cands:
        return None
    cands = sorted(cands, key=lambda c: (c["primary"], vkey(c["version"])), reverse=True)
    return cands[0]


def resolve_any(token, domain, idx, refs):
    """Any provenance token -> a linkable target dict, or None.
    - kb:     -> resolve() (unchanged — the primary/newest reference note)
    - ref:    -> the exact references/<name>.md curated guide (a trailing .md on the token is
                 optional; no other normalization — a path or wrong name is a reported miss)
    - guide:  -> the generated per-guide index note reference/<domain>/_ref-<domain>-<slug>.md
    - web:/note: -> None (no 1:1 in-vault note), never counted as unresolved."""
    if token.startswith("kb:"):
        return resolve(token, domain, idx)
    if token.startswith("ref:"):
        name = token[len("ref:"):]
        if name.endswith(".md"):
            name = name[:-3]
        return refs.get(name)
    if token.startswith("guide:"):
        key = "_ref-%s-%s" % (domain, token[len("guide:"):])
        cands = (idx.get(domain) or {}).get(key)
        return cands[0] if cands else None
    return None


def short_title(t):
    # strip chars that would break a [[slug|alias]] (titles like "[RHBK] ..." contain ])
    return re.sub(r"[\[\]|#]", "", (t or "").split(" - ")[0]).strip()


def build_section(links):
    body = "\n".join(f"- [[{slug}|{short_title(title)}]]" for slug, title in links)
    return f"\n\n## Sources\n{BEGIN}\n{body}\n{END}\n"


def apply_section(text, links):
    if links:
        block = build_section(links)
        if SECTION_RE.search(text):
            return SECTION_RE.sub(block, text)
        return text.rstrip() + block
    # no links: strip any stale generated section
    return SECTION_RE.sub("\n", text) if SECTION_RE.search(text) else text


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--apply", action="store_true")
    args = ap.parse_args()

    idx = build_ref_index()
    refs = build_refs_index()
    pages_linked = edges = 0
    unresolved = {}
    sample = None

    for d in PAGE_DIRS:
        full = os.path.join(WIKI, d)
        if not os.path.isdir(full):
            continue
        for fn in sorted(os.listdir(full)):
            if not fn.endswith(".md") or fn == "README.md":
                continue
            path = os.path.join(full, fn)
            text = open(path, encoding="utf-8").read()
            m = FM_RE.match(text)
            if not m:
                continue
            fm = top_fields(m.group(1))
            domain = fm.get("domain")
            links, seen = [], set()
            for tok in source_tokens(m.group(1)):
                r = resolve_any(tok, domain, idx, refs)
                if r and r["slug"] not in seen:
                    seen.add(r["slug"])
                    links.append((r["slug"], r["title"]))
                elif tok.startswith(("kb:", "ref:", "guide:")) and not r:
                    unresolved[tok] = unresolved.get(tok, 0) + 1
            if links:
                pages_linked += 1
                edges += len(links)
                if sample is None:
                    sample = (fn[:-3], links)
            new = apply_section(text, links)
            if args.apply and new != text:
                with open(path, "w", encoding="utf-8") as fh:
                    fh.write(new)

    print(f"{'WROTE' if args.apply else 'DRY RUN'} — {pages_linked} pages → {edges} wiki→KB edges")
    # kb: misses are an invariant (selftest #6: every kb: token resolves); ref:/guide: misses are
    # a report — mis-tiered names/paths on existing pages, fixed by editing the page, not the tool.
    for label, pred in (("kb:", lambda t: t.startswith("kb:")),
                        ("ref:/guide:", lambda t: not t.startswith("kb:"))):
        part = {t: n for t, n in unresolved.items() if pred(t)}
        if part:
            top = sorted(part.items(), key=lambda kv: -kv[1])[:8]
            print(f"unresolved {label} tokens (no matching note/guide — gated ids, mis-tiered "
                  f"names, paths): {len(part)} distinct; e.g. "
                  + ", ".join(f"{t}×{n}" for t, n in top))
    if sample:
        slug, links = sample
        print(f"\nsample — {slug}.md ## Sources:")
        for s, t in links:
            print(f"  - [[{s}|{short_title(t)}]]")
    if not args.apply:
        print("\nRe-run with --apply to write.")


if __name__ == "__main__":
    main()
