#!/usr/bin/env python3
"""graphlinks.py — write Graphify's computed communities back into Obsidian.

The Obsidian -> Graphify direction is `sync-graph.sh`: crosslink/index/tkg build the
curated wiki graph, `graphify_export.py` writes it to `graphify-out/graph.json`, then
`graphify cluster-only` runs Leiden clustering and stamps each node with a `community`
(int) and `community_name` (str). This module is the REVERSE flow: it reads that
computed community back onto the wiki page it came from, so Obsidian's own file
relations (Bases views, the graph color groups) gain Graphify's clustering on top of
the hand-curated `[[wikilinks]]` — the two layers stay complementary instead of the
computed one being stranded in a side JSON file nobody opens.

Two writes, both idempotent and generated (never hand-edit their output):
  1. `graph_community: "<name>"` frontmatter key on every topics/entities/questions
     page whose node carries a `community_name` in the graph; removed from pages
     whose node no longer appears (a full reconcile, not just an upsert).
  2. `.obsidian/graph.json`'s `colorGroups` — one color group per the TOP_N_COLOR_GROUPS
     largest communities, `["graph_community":"<name>"]` query syntax — so the graph view
     colors by cluster. Best-effort: a missing/unparseable file is a warning, not a
     crash (Obsidian workspace files vary; this is a convenience, not a contract).
     **This half is NOT durable while Obsidian runs.** `graph.json` is Obsidian-owned —
     the app keeps the graph config in memory and rewrites the file on quit, silently
     dropping our `colorGroups` back to `[]` (write #1 is unaffected: it lives in the
     pages themselves, in git). Apply with Obsidian CLOSED; `obsidian_running()` warns
     when it isn't, so the tool can't print WROTE for a write that will be discarded.

Never touches reference/, references/, or _sources/ (immutable tiers), and never
bumps `updated:` — this is a generated annotation, like crosslink's `## Sources`.

Usage:
    python3 -m wikikb graphlinks            # dry-run: counts + a few samples
    python3 -m wikikb graphlinks --apply    # write frontmatter + graph.json colorGroups
"""
import argparse
import subprocess
import colorsys
import json
import os
import re

from wikikb import paths

WIKI = str(paths.WIKI)
GRAPH_JSON = os.path.join(WIKI, "graphify-out", "graph.json")
# The vault Obsidian actually opens may be WIKI or the repo root above it (the user's
# live vault is the repo root — its .obsidian/ carries the workspace.json). Update
# every existing candidate so colors land wherever the graph view reads them.
OBSIDIAN_GRAPH_JSONS = [
    os.path.join(str(p), ".obsidian", "graph.json")
    for p in dict.fromkeys((paths.WIKI, paths.ROOT))
]
PAGE_DIRS = paths.PAGE_DIRS
FM_RE = re.compile(r"^(---\n)(.*?)(\n---)", re.DOTALL)
FIELD_RE = re.compile(r"^graph_community:.*$", re.MULTILINE)
TOP_N_COLOR_GROUPS = None  # ALL communities. A fixed cap silently leaves the newest/smallest
                           # community uncolored every time clustering grows (it was 10, then 24,
                           # and clustering just produced 25) — the palette is generated by even
                           # hue spacing, so it scales without a magic number to keep bumping.


def load_graph():
    """{source_file (vault-relative) -> community_name} for topic/entity/question nodes."""
    if not os.path.isfile(GRAPH_JSON):
        print("graphlinks ▸ %s not found — run `sh _meta/sync-graph.sh` first "
              "(needs `graphify cluster-only` to have run)." % GRAPH_JSON)
        raise SystemExit(1)
    d = json.loads(open(GRAPH_JSON, encoding="utf-8").read())
    names = _hub_names(d)
    by_file = {}
    for n in d.get("nodes", []):
        if n.get("kind") not in ("topic", "entity", "question"):
            continue
        name = n.get("community_name")
        if name:
            by_file[n["source_file"]] = names.get(name, name)
    return by_file


GENERIC_NAME_RE = re.compile(r"^Community \d+$")


def _hub_names(d):
    """{generic community_name -> hub label}. A `--no-label` clustering run stamps
    generic names ("Community 7"); name those after the community's highest-degree
    page node (its hub) so the frontmatter value means something. Labeled runs
    pass through untouched."""
    degree = {}
    for e in d.get("links", []):
        for k in (e.get("source"), e.get("target")):
            degree[k] = degree.get(k, 0) + 1
    best = {}  # community_name -> (degree, label)
    for n in d.get("nodes", []):
        name = n.get("community_name")
        if not name or not GENERIC_NAME_RE.match(name):
            continue
        if n.get("kind") not in ("topic", "entity", "question"):
            continue
        cand = (degree.get(n["id"], 0), n.get("label") or n["id"])
        # deterministic: higher degree wins, then lexicographically first label
        cur = best.get(name)
        if cur is None or cand[0] > cur[0] or (cand[0] == cur[0] and cand[1] < cur[1]):
            best[name] = cand
    return {name: label for name, (_, label) in best.items()}


def edit_frontmatter(text, transform):
    m = FM_RE.match(text)
    if not m:
        return text, False
    new_block, changed = transform(m.group(2))
    if not changed:
        return text, False
    return text[:m.start()] + m.group(1) + new_block + m.group(3) + text[m.end():], True


def upsert_community(block, name):
    line = 'graph_community: "%s"' % name
    if FIELD_RE.search(block):
        if FIELD_RE.search(block).group(0) == line:
            return block, False
        return FIELD_RE.sub(line, block, count=1), True
    return block.rstrip("\n") + "\n" + line, True


def remove_community(block):
    if not FIELD_RE.search(block):
        return block, False
    new = FIELD_RE.sub("", block, count=1)
    new = re.sub(r"\n\n+", "\n", new)
    return new, True


def sync_pages(by_file, apply_):
    n_upsert = n_remove = 0
    samples = []
    for d in PAGE_DIRS:
        full = os.path.join(WIKI, d)
        if not os.path.isdir(full):
            continue
        for fn in sorted(os.listdir(full)):
            if not fn.endswith(".md") or fn == "README.md":
                continue
            rel = "%s/%s" % (d, fn)
            path = os.path.join(full, fn)
            with open(path, encoding="utf-8") as fh:
                text = fh.read()
            name = by_file.get(rel)
            tf = (lambda block, name=name: upsert_community(block, name)) if name else remove_community
            new_text, changed = edit_frontmatter(text, tf)
            if not changed:
                continue
            if name:
                n_upsert += 1
            else:
                n_remove += 1
            if len(samples) < 5:
                samples.append("%s -> %r" % (rel, name))
            if apply_:
                with open(path, "w", encoding="utf-8") as fh:
                    fh.write(new_text)
    return n_upsert, n_remove, samples


def hue_color(i, total, sat=0.65, val=0.9):
    """Evenly spaced hue -> Obsidian's {"a":1,"rgb":<int>} color encoding."""
    r, g, b = colorsys.hsv_to_rgb(i / max(total, 1), sat, val)
    rgb = (int(r * 255) << 16) | (int(g * 255) << 8) | int(b * 255)
    return {"a": 1, "rgb": rgb}


def reference_domains():
    """Sorted `reference/<domain>/` names. The raw tier can't carry `graph_community:`
    (it is IMMUTABLE — CLAUDE.md: writes go only to the synthesis layer), so it is
    coloured by PATH instead of by cluster. Sorted ⇒ a domain keeps its hue across runs."""
    ref = str(paths.REFERENCE)
    if not os.path.isdir(ref):
        return []
    return sorted(d for d in os.listdir(ref) if os.path.isdir(os.path.join(ref, d)))


def build_color_groups(by_file):
    counts = {}
    for name in by_file.values():
        counts[name] = counts.get(name, 0) + 1
    top = sorted(counts.items(), key=lambda kv: -kv[1])[:TOP_N_COLOR_GROUPS]
    groups = [
        {"query": '["graph_community":"%s"]' % name, "color": hue_color(i, len(top))}
        for i, (name, _) in enumerate(top)
    ]
    # raw tiers last (first match wins in Obsidian): DESATURATED colors so the immutable
    # KB visually recedes behind the colored synthesis communities. One group per
    # reference/<domain>/ — the raw tier cannot be clustered into communities (its notes
    # are immutable, so `graph_community:` can never be written there), so path IS the
    # only grouping available to it. Same even-hue spacing at low saturation: a domain's
    # 4,000 raw notes read as one washed-out field behind its vivid synthesis cluster.
    domains = reference_domains()
    for i, dom in enumerate(domains):
        groups.append({"query": "path:reference/%s/" % dom,
                       "color": hue_color(i, len(domains), sat=0.28, val=0.72)})
    groups.append({"query": "path:reference/", "color": {"a": 1, "rgb": 0x888888}})
    groups.append({"query": "path:references/", "color": {"a": 1, "rgb": 0x4A6B8A}})
    return groups


def obsidian_running():
    """True if the Obsidian app is up. `.obsidian/graph.json` is OBSIDIAN-OWNED: the app holds
    the graph config in memory and rewrites the file on quit (and on settings changes), so a
    write we make while it is running is silently discarded — the tool prints WROTE and the
    user sees an uncolored graph. Detection is best-effort; unknown ⇒ False (warn nothing)."""
    try:
        return subprocess.run(["pgrep", "-x", "Obsidian"], capture_output=True).returncode == 0
    except (OSError, ValueError):                      # no pgrep (non-macOS/Linux) — stay quiet
        return False


OBSIDIAN_WORKSPACES = [
    os.path.join(str(p), ".obsidian", "workspace.json")
    for p in dict.fromkeys((paths.WIKI, paths.ROOT))
]

# Graph-view filter. The raw tiers are ~28k notes against ~476 synthesis pages, and 189 generated
# `_ref-*` index notes each fan out to hundreds of KB notes — so with them in view the graph is a
# gray hairball of starbursts and the colored synthesis communities are invisible inside it. This
# filters the GRAPH ONLY: the notes stay fully present in search, quick-switcher, and the file
# explorer (unlike .obsidian/app.json's userIgnoreFilters, which hides them everywhere). Clear it
# any time by emptying the graph's search box.
GRAPH_SEARCH_FILTER = "-path:reference/ -path:_sources/ -path:references/"


def sync_obsidian_workspace(groups, apply_):
    """Write the SAME colorGroups into the open graph pane's saved state in workspace.json.

    `.obsidian/graph.json` alone is not enough and this is why the colours kept vanishing:
    graph.json holds the DEFAULTS for a newly opened graph view, but an ALREADY-OPEN graph
    pane carries its own copy in workspace.json. On startup Obsidian restores that pane —
    whose saved state here was literally `{}` — and then persists the restored (empty)
    settings back over graph.json, wiping the groups. Patching both means the restored pane
    already has them, so there is nothing left to overwrite them with.

    Obsidian owns this file too: apply with the app CLOSED (obsidian_running() warns)."""
    touched = 0
    for path in OBSIDIAN_WORKSPACES:
        if not os.path.isfile(path):
            continue
        try:
            ws = json.loads(open(path, encoding="utf-8").read())
        except (OSError, ValueError) as e:
            print("graphlinks ▸ WARN: could not parse %s (%s) — skipping graph-pane state." % (path, e))
            continue
        hits = []

        def walk(node):
            if isinstance(node, dict):
                st = node.get("state")
                if isinstance(st, dict) and st.get("type") == "graph":
                    hits.append(st.setdefault("state", {}))
                for v in node.values():
                    walk(v)
            elif isinstance(node, list):
                for v in node:
                    walk(v)

        walk(ws)
        changed = [s for s in hits
                   if s.get("colorGroups") != groups or s.get("search") != GRAPH_SEARCH_FILTER]
        for s in changed:
            s["colorGroups"] = groups
            s["search"] = GRAPH_SEARCH_FILTER
        if changed and apply_:
            with open(path, "w", encoding="utf-8") as fh:
                json.dump(ws, fh, indent=2)
                fh.write("\n")
        touched += len(changed)
    return touched


def sync_obsidian_graph(by_file, apply_):
    groups = build_color_groups(by_file)
    found = changed = False
    for path in OBSIDIAN_GRAPH_JSONS:
        if not os.path.isfile(path):
            continue
        try:
            cfg = json.loads(open(path, encoding="utf-8").read())
        except (OSError, ValueError) as e:
            print("graphlinks ▸ WARN: could not parse %s (%s) — skipping colorGroups."
                  % (path, e))
            continue
        found = True
        if cfg.get("colorGroups") == groups and cfg.get("search") == GRAPH_SEARCH_FILTER:
            continue
        changed = True
        cfg["colorGroups"] = groups
        cfg["search"] = GRAPH_SEARCH_FILTER
        if apply_:
            with open(path, "w", encoding="utf-8") as fh:
                json.dump(cfg, fh, indent=2)
                fh.write("\n")
    if not found:
        print("graphlinks ▸ WARN: no .obsidian/graph.json found in %s — skipping colorGroups."
              % ", ".join(OBSIDIAN_GRAPH_JSONS))
        return None
    return groups, changed


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--apply", action="store_true")
    args = ap.parse_args()

    if args.apply:
        err = paths.eval_lock_error()
        if err:
            print("graphlinks ▸ REFUSED: " + err)
            raise SystemExit(2)

    by_file = load_graph()
    n_upsert, n_remove, samples = sync_pages(by_file, args.apply)
    groups, groups_changed = sync_obsidian_graph(by_file, args.apply) or (None, False)

    verb = "WROTE" if args.apply else "DRY RUN"
    print("%s — %d pages to tag graph_community, %d stale tags to remove"
          % (verb, n_upsert, n_remove))
    for s in samples:
        print("  - " + s)
    if groups is not None:
        panes = sync_obsidian_workspace(groups, args.apply)
        print("%s — colorGroups: %d groups (%s); %d open graph pane(s) re-stated"
              % (verb, len(groups), "changed" if groups_changed else "unchanged", panes))
        # The frontmatter half of the round-trip is durable (it lives in the pages, in git).
        # The colorGroups half is not: Obsidian OWNS .obsidian/graph.json and rewrites it from
        # memory, so applying while it runs is a write we lose. Say so instead of printing WROTE.
        if args.apply and groups_changed and obsidian_running():
            print("graphlinks ▸ WARN: Obsidian is RUNNING — it owns .obsidian/graph.json and "
                  "rewrites it from memory, so these colorGroups will be discarded on quit. "
                  "Quit Obsidian, re-run `python3 -m wikikb graphlinks --apply`, then reopen.")
    if not args.apply:
        print("\nRe-run with --apply to write.")


if __name__ == "__main__":
    main()
